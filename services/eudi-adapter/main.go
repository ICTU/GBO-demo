func loadConfig() config {
	refresh, err := time.ParseDuration(getEnv("SOURCE_REGISTRY_REFRESH_INTERVAL", "5s"))
	if err != nil || refresh <= 0 {
		refresh = 5 * time.Second
	}
	return config{
		Port:                      getEnv("PORT", "4009"),
		OutwayURL:                 getEnv("FSC_OUTWAY_URL", "http://edi-outway:8080"),
		SourceRegistryDatabaseURL: os.Getenv("SOURCE_REGISTRY_DATABASE_URL"),
		SourceRegistrySchema:      getEnv("SOURCE_REGISTRY_SCHEMA", "source_registry"),
		SourceRegistryRefresh:     refresh,
	}
}

func getEnv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// issuanceServerRequest supports the two disclosure shapes used by the
// issuance integration:
//   - `attributes.urn:eudi:pid:nl:1.bsn` (nested, real PID sd-jwt)
//   - `attributes.bsn` (flat, test shape)
//
// We decode as `map[string]any` so both shapes can be scanned.
type issuanceServerRequest []struct {
	Attestations []struct {
		AttestationType string         `json:"attestation_type"`
		Attributes      map[string]any `json:"attributes"`
	} `json:"attestations"`
	ID string `json:"id"`
}

// extractBSN scans the attributes map for a BSN: first nested under the PID
// namespace, then flat.
func extractBSN(attrs map[string]any) string {
	if nested, ok := attrs["urn:eudi:pid:nl:1"].(map[string]any); ok {
		if s, ok := nested["bsn"].(string); ok {
			return s
		}
	}
	if s, ok := attrs["bsn"].(string); ok {
		return s
	}
	// Fallback: any one-level-deeper map with "bsn".
	for _, v := range attrs {
		if m, ok := v.(map[string]any); ok {
			if s, ok := m["bsn"].(string); ok {
				return s
			}
		}
	}
	return ""
}

// attestation is the generic shape consumed by the issuance-server. It
// expects a flat array without an envelope; credential metadata is resolved
// from the generated issuance configuration.
type attestation struct {
	AttestationType string         `json:"attestation_type"`
	Attributes      map[string]any `json:"attributes"`
	Format          string         `json:"format"`
	ID              string         `json:"id"`
}

// proxyRequest is the GraphQL body that FSC forwards to the source. Trusted
// authorization context, including the flow, comes from the FSC token.
type proxyRequest struct {
	Query     string         `json:"query"`
	Variables map[string]any `json:"variables,omitempty"`
}

// graphqlResponse only inspects the protocol-level error envelope. Projection
// of the data body is fully driven by the activated source metadata.
type graphqlResponse struct {
	Errors []map[string]any `json:"errors,omitempty"`
}

type sourceQueryPlan struct {
	ServiceReference string
	Endpoint         string
	Query            string
	Variables        map[string]any
}

type fscResult struct {
	Raw []byte
}

// handleSourceAttestation is the only issuance path for onboarded types. The
// route selects an activated source/type; concrete parameter values come from
// the issuance request URL and are validated against the source declaration.
func handleSourceAttestation(cfg config, client *http.Client, runtime sourceMetadataRuntime, logbook *issuanceLogbook) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		now := time.Now()
		// Two Dataverwerkingen happen below: reading the BSN out of the
		// disclosed PID, and assembling the attestation from what the source
		// returned. Both are GBO's own, both are logged, and neither delivers
		// if its record is not confirmed.
		extractionStart := time.Now().UTC()
		var recording issuanceRecording
		resolved := cfg
		var metadata *activeSourceMetadata
		var err error
		if activated, ok := runtime.(interface {
			currentSource(time.Time) (*activeSourceMetadata, config, error)
		}); ok {
			metadata, resolved, err = activated.currentSource(now)
		} else {
			metadata, err = runtime.current(now)
		}
		if err != nil {
			logSourceAttestationError(r, "metadata", err)
			http.Error(w, "source metadata unavailable", http.StatusServiceUnavailable)
			return
		}
		if r.PathValue("sourceID") != metadata.SourceID || r.PathValue("typeID") != metadata.TypeID {
			http.NotFound(w, r)
			return
		}
		if metadata.CacheState != "" {
			w.Header().Set("X-GBO-Metadata-Cache", metadata.CacheState)
		}
		body, err := io.ReadAll(io.LimitReader(r.Body, 4<<20))
		if err != nil {
			logSourceAttestationError(r, "read_request", err)
			http.Error(w, "invalid issuance request", http.StatusBadRequest)
			return
		}
		var request issuanceServerRequest
		if err := json.Unmarshal(body, &request); err != nil || len(request) == 0 || len(request[0].Attestations) == 0 {
			if err == nil {
				err = fmt.Errorf("issuance request contains no disclosed attestation")
			}
			logSourceAttestationError(r, "decode_request", err)
			http.Error(w, "invalid PID disclosure", http.StatusBadRequest)
			return
		}
		bsn := extractBSN(request[0].Attestations[0].Attributes)
		if bsn == "" {
			logSourceAttestationError(r, "extract_subject", fmt.Errorf("disclosed PID contains no BSN"))
			http.Error(w, "no BSN in disclosed PID", http.StatusBadRequest)
			return
		}
		// Logged before the source is called: a request that cannot be logged
		// must not reach the bronhouder at all.
		if logbook != nil {
			recording, err = logbook.logPIDExtraction(r.Context(), r, bsn, extractionStart, metadata.SourceID, metadata.TypeID)
			if err != nil {
				http.Error(w, "the PID disclosure could not be logged; refusing the request", http.StatusInternalServerError)
				return
			}
		}
		plan, err := metadata.queryPlan(bsn, r.URL.Query())
		if err != nil {
			logSourceAttestationError(r, "parameters", err)
			http.Error(w, "invalid attestation parameters", http.StatusBadRequest)
			return
		}
		trace.SpanFromContext(r.Context()).SetAttributes(
			attribute.String("gbo.source_id", metadata.SourceID),
			attribute.String("gbo.source_oin", metadata.SourceOIN),
			attribute.String("gbo.type_id", metadata.TypeID),
		)
		result, err := callSource(r.Context(), client, resolved, plan)
		if err != nil {
			logSourceAttestationError(r, "source_request", err)
			http.Error(w, "source request failed", http.StatusBadGateway)
			return
		}
		assemblyStart := time.Now().UTC()
		projection, err := metadata.project(result.Raw)
		if err != nil {
			logSourceAttestationError(r, "projection", err)
			http.Error(w, "source response could not be projected", http.StatusBadGateway)
			return
		}
		if projection.Outcome == gbosimplev1.OutcomeNoData {
			http.Error(w, "source has no data for this subject and parameters", http.StatusNotFound)
			return
		}
		// The attestation exists now; it does not leave this process until
		// the logbook has said so.
		if logbook != nil {
			if err := logbook.logAttestationAssembly(r.Context(), recording, assemblyStart,
				metadata.SourceID, metadata.TypeID, metadata.SourceOIN, len(projection.Claims)); err != nil {
				http.Error(w, "the attestation could not be logged; withholding it", http.StatusInternalServerError)
				return
			}
		}
		// nl-wallet turns attestation_type into the credential's vct and
		// computes vct#integrity from the installed Type Metadata bytes. Both
		// are internal claims and must not be supplied as ordinary attributes.
		documents := []attestation{{
			AttestationType: metadata.VCT,
			Attributes:      projection.Claims,
			Format:          "dc+sd-jwt",
			ID:              uuid.NewString(),
		}}
		w.Header().Set("Content-Type", "application/json")
		if err := json.NewEncoder(w).Encode(documents); err != nil {
			slog.Error("encode source attestation response", "err", err.Error())
		}
	}
}

func logSourceAttestationError(r *http.Request, stage string, err error) {
	slog.Error("source attestation request failed",
		"stage", stage,
		"source_id", r.PathValue("sourceID"),
		"type_id", r.PathValue("typeID"),
		"err", err.Error(),
	)
}

