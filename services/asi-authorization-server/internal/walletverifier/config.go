package walletverifier

import (
	"fmt"
	"strings"
)

// Config is the verification_server configuration the authorization server
// needs: one usecase, sessions in memory, the internal API behind an API key.
type Config struct {
	PublicURL, UniversalLinkBase string
	IssuerAnchors, ReaderAnchors []string
	EphemeralIDSecret, APIKey    string
	ReaderKey, ReaderCertificate string
}

// TOML renders the configuration. The wallet port (8001) is public; the
// internal port (8002) is for the authorization server only.
func (c Config) TOML() string {
	quote := func(xs []string) string {
		q := make([]string, len(xs))
		for i, x := range xs {
			q[i] = fmt.Sprintf("%q", x)
		}
		return "[" + strings.Join(q, ", ") + "]"
	}
	return fmt.Sprintf(`# Generated by asi-authorization-server provision-wallet-verifier.
structured_logging = true
ephemeral_id_secret = %q
issuer_trust_anchors = %s
reader_trust_anchors = %s
public_url = %q
universal_link_base_url = %q
wallet_client_ids = ["https://wallet.edi.rijksoverheid.nl"]

[wallet_server]
ip = "0.0.0.0"
port = 8001

[internal_server]
ip = "0.0.0.0"
port = 8002

[internal_server.authentication]
api_key = %q

[storage]
url = "memory://"

[usecases.%s]
private_key_type = "software"
private_key = %q
certificate = %q
session_type_return_url = "neither"
accept_undetermined_revocation_status = true
`, c.EphemeralIDSecret, quote(c.IssuerAnchors), quote(c.ReaderAnchors), c.PublicURL, c.UniversalLinkBase, c.APIKey, Usecase, c.ReaderKey, c.ReaderCertificate)
}
