package walletverifier

import (
	"fmt"
	"strings"
)

// Config is the verification_server configuration: a usecase per relying
// party, sessions in memory, the internal API behind an API key.
type Config struct {
	PublicURL, UniversalLinkBase string
	IssuerAnchors, ReaderAnchors []string
	EphemeralIDSecret, APIKey    string
	Usecases                     []UsecaseConfig
}

// UsecaseConfig is a usecase with the reader certificate the wallet shows.
type UsecaseConfig struct {
	Name, ReaderKey, ReaderCertificate string
}

// TOML renders the configuration. The wallet port (8001) is for the wallet;
// the internal port (8002) for the relying parties, with the API key.
func (c Config) TOML() string {
	quote := func(xs []string) string {
		q := make([]string, len(xs))
		for i, x := range xs {
			q[i] = fmt.Sprintf("%q", x)
		}
		return "[" + strings.Join(q, ", ") + "]"
	}
	var usecases strings.Builder
	for _, u := range c.Usecases {
		fmt.Fprintf(&usecases, `
[usecases.%s]
private_key_type = "software"
private_key = %q
certificate = %q
session_type_return_url = "neither"
accept_undetermined_revocation_status = true
`, u.Name, u.ReaderKey, u.ReaderCertificate)
	}
	return fmt.Sprintf(`# Generated by asi-authorization-server provision-wallet-verifier.
structured_logging = true
ephemeral_id_secret = %q
issuer_trust_anchors = %s
reader_trust_anchors = %s
public_url = %q
universal_link_base_url = %q
wallet_client_ids = ["https://wallet.edi.rijksoverheid.nl"]

[wallet_server]
ip = "0.0.0.0"
port = 8001

[internal_server]
ip = "0.0.0.0"
port = 8002

[internal_server.authentication]
api_key = %q

[storage]
url = "memory://"
%s`, c.EphemeralIDSecret, quote(c.IssuerAnchors), quote(c.ReaderAnchors), c.PublicURL, c.UniversalLinkBase, c.APIKey, usecases.String())
}
