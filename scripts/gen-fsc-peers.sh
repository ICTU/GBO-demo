#!/usr/bin/env bash
# Regenerates policies/gbo/fsc_peers.rego: the FSC peer ID of every party in
# fsc-infra/peers.txt, keyed by the party's name. The policies read a
# party's peer ID from there instead of writing it out, so a change to
# peers.txt reaches them through this one file. Run after changing
# peers.txt (make fsc-peers); scripts/check-fsc-peers.sh fails when the
# file is stale.
#
#   scripts/gen-fsc-peers.sh          write policies/gbo/fsc_peers.rego
#   scripts/gen-fsc-peers.sh FILE     write FILE instead
#
# Reads the table through `bootstrap-peer.sh --list`, its one reader. Needs
# only bash: no Docker, no OPA.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT="${1:-policies/gbo/fsc_peers.rego}"

rows="$(cd fsc-infra/pki && bash bootstrap-peer.sh --list)"

{
	cat <<'EOF'
# Code generated by scripts/gen-fsc-peers.sh from fsc-infra/peers.txt. DO NOT EDIT.
#
# The FSC peer ID (the OIN in the group certificate) of every party of the
# demo, keyed by its name in fsc-infra/peers.txt. Policies read a party's
# peer ID from here, so they follow peers.txt.
package gbo.fsc_peers

peer_ids := {
EOF
	while IFS=$'\t' read -r name _dir oin _rest; do
		if [[ ! "${name}" =~ ^[a-z0-9-]+$ || ! "${oin}" =~ ^[0-9]{20}$ ]]; then
			echo "gen-fsc-peers: unexpected row in fsc-infra/peers.txt: ${name} ${oin}" >&2
			exit 1
		fi
		printf '\t"%s": "%s",\n' "${name}" "${oin}"
	done <<<"${rows}"
	echo "}"
} >"${OUT}.tmp"
mv "${OUT}.tmp" "${OUT}"
